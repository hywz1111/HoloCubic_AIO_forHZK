#!/usr/bin/env python3
"""Generate monochrome name labels; requires Pillow and a Noto Sans CJK font."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont


def bitmap(text, size, font_path):
    font = ImageFont.truetype(str(font_path), size, index=0)
    box = font.getbbox(text)
    width, height = box[2] - box[0], box[3] - box[1]
    image = Image.new("1", (width, height))
    ImageDraw.Draw(image).text((-box[0], -box[1]), text, font=font, fill=1)
    data = []
    for y in range(height):
        for x in range(0, width, 8):
            value = 0
            for bit in range(8):
                if x + bit < width and image.getpixel((x + bit, y)):
                    value |= 0x80 >> bit
            data.append(value)
    return width, height, data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    lines = ["// Generated by tools/generate_name.py; Noto Sans CJK, SIL OFL 1.1.",
             "#pragma once", "#include <Arduino.h>"]
    for name, text, size in (("Name", "晗歌", 46), ("Kana", "はづき", 26),
                             ("EventTitle", "纪念日", 22), ("EventEmpty", "在手机添加纪念日", 18),
                             ("Today", "就是今天", 30), ("Before", "还有", 20),
                             ("After", "已经过", 20), ("Day", "天", 20),
                             ("NoteTitle", "今日留言", 22), ("NoteEmpty", "在手机写一句话", 18),
                             ("Remaining", "剩余时间", 22), ("TimerDone", "时间到啦", 32),
                             ("Dismiss", "在手机点结束计时", 18)):
        width, height, data = bitmap(text, size, args.font)
        lines += [f"constexpr int {name}Width = {width}, {name}Height = {height};",
                  f"static const uint8_t {name}Bitmap[] PROGMEM = {{"]
        for start in range(0, len(data), 16):
            lines.append("    " + ",".join(f"0x{n:02x}" for n in data[start:start + 16]) + ",")
        lines.append("};")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
